class MangleKeyData:
    """Port of encryption.MangleKeyData: a 16-byte read-only key."""

    __slots__ = ("_data",)

    def __init__(self, data=None):
        if data is None:
            data = bytes(16)
        self._data = bytes(data)

    @property
    def data(self):
        return self._data

    def round_key(self, round_):
        return struct.unpack_from("<I", self._data, (round_ & 3) << 2)[0]


